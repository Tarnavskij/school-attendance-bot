# core/validators.py
"""
Единая точка валидации пользовательского текстового ввода,
который попадает в БД и может позже отображаться в веб-панели
или экспортироваться в Excel.

Используется везде, где создаётся/переименовывается:
- ученик (create_student)
- класс (создание класса при импорте)
- школа (create_school, rename_school)
"""
import re

# Запрещаем угловые скобки (HTML/XSS), двойные кавычки, обратные слеши,
# управляющие символы. Разрешаем буквы (кириллица/латиница), цифры,
# пробел, дефис, точку, апостроф, круглые скобки (для "5А (доп.)"),
# а также символы, реально встречающиеся в названиях школ:
# № « » : / ! (например, «Гимназия №5», «СШ им. Ленина: корпус 2», «Школа №1/2»).
_SAFE_TEXT_RE = re.compile(r"^[A-Za-zА-ЯЁа-яё0-9 .,'\-()№«»:/!]{1,100}$")

# Символы, которые Excel/LibreOffice может интерпретировать как начало
# формулы (Excel/CSV Injection).
_FORMULA_TRIGGER_CHARS = ("=", "+", "-", "@", "\t", "\r")


class ValidationError(ValueError):
    """Выбрасывается, если текст не прошёл проверку."""
    pass


def validate_safe_text(value: str, field_name: str = "поле", max_len: int = 100) -> str:
    """
    Проверяет и возвращает "очищенный" текст (strip).
    Бросает ValidationError с понятным сообщением, если текст не прошёл проверку.

    ВАЖНО: эта функция не изменяет смысл текста, только:
    1) убирает пробелы по краям (strip)
    2) проверяет длину
    3) проверяет, что нет запрещённых символов (<, >, ", \\, и пр.)
    """
    if value is None:
        raise ValidationError(f"{field_name}: значение не может быть пустым.")

    cleaned = value.strip()

    if not cleaned:
        raise ValidationError(f"{field_name}: значение не может быть пустым.")

    if len(cleaned) > max_len:
        raise ValidationError(f"{field_name}: превышена максимальная длина ({max_len}).")

    if not _SAFE_TEXT_RE.match(cleaned):
        raise ValidationError(
            f"{field_name}: разрешены только буквы, цифры, пробел, дефис, "
            f"точка, апостроф и круглые скобки."
        )

    return cleaned


def excel_safe(value: str) -> str:
    """
    Возвращает текст, безопасный для записи в ячейку Excel.
    Если значение начинается с символа, который Excel может принять
    за начало формулы (=, +, -, @), добавляет ведущий апостроф,
    который заставляет Excel показать текст "как есть", а не вычислять его.

    Использовать ТОЛЬКО перед записью значения в ячейку openpyxl
    (ws.append(...) / ws.cell(..., value=...)).
    Не использовать для валидации при сохранении в БД — это отдельная функция.
    """
    if value is None:
        return value
    text = str(value)
    if text.startswith(_FORMULA_TRIGGER_CHARS):
        return "'" + text
    return text
